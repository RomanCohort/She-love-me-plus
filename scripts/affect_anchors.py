"""
affect_anchors.py - 情感轴的锚句集（semantic projection 的方向定义）

方法出处
--------
Grand, Blank, Pereira & Fedorenko (2022), "Semantic projection recovers rich
human knowledge of multiple object features from word embeddings",
*Nature Human Behaviour* 6, 975–987.

做法：写一组**人读得懂**的锚句，取它们句向量的均值差得到一条语义轴（如「效价轴」），
把任意句子投影上去就是连续分数。相比训一个情感回归模型：零新模型（复用已有句向量
后端）、可解释（轴就是下面这些句子）、可审计（嫌轴歪了改句子就行，不用重训）。

构造原则（别随手加句子破坏它）
------------------------------
- **效价轴**：左右两侧**逐句平行**——同话题、同句式，只翻情绪极性。这样均值差里
  剩下的才只有效价成分，不会混进话题或句长的差异。
- **唤醒轴**：左右两侧**各自正负配平**（高唤醒侧既有「我太兴奋了」也有「气死我了」；
  低唤醒侧既有「挺舒服的」也有「提不起劲」）。正负相消之后轴上剩下的才是唤醒度，
  否则「唤醒轴」会退化成第二个「效价轴」。

自检：投影前先看 `affect.axis_diagnostic()` 报的两轴相关系数。应当接近正交；
若 |r| 逼近 1，说明唤醒锚句的配平被破坏了。

锚句是实验选出来的，不是拍脑袋写的
----------------------------------
初版锚句里「好」字出现太密（好幸福啊 / 太好了吧 / 你真好），结果整条效价轴学到的
是「好」这个**字面**而不是正向情绪——语料里投影最正的一批变成了「好！」「噢噢好」
「好呀好呀」，而「好！」作为应答根本不热情。

换成下面这版（逐句平行、但不再复用同一批字面，且每条改写成具体情境）之后，
最正的一批变成了「恭喜恭喜」「谢谢啦」「很可爱对吧」——才是真正向的对话。
两版在同一条语料上的对照见 commit 说明。

**已知弱点：疲惫类表达在这条轴上偏中性——这是二维模型的理论边界，不是缺陷。**
实测：「好累啊」投影 -0.014、「我真的好累」-0.032、「心累」-0.123。补三对疲劳类
锚句也几乎不动（-0.014 → -0.021）。

原因在维度模型本身，不在锚句覆盖：疲惫是**低唤醒 + 效价不明确**的状态，而
效价-唤醒二维平面本来就把「累」这类情绪放在靠近中轴的位置——它既不是愉快也不是
不愉快，只是没力气。Russell 环形模型对这类状态的区分度天然有限。这类词请走
`lexicon.py` 那条路（词表在「有没有『累』」上比任何模型都准）。
"""

