"""
semantic_anchors.py - 效价/唤醒之外的语义轴锚句集

与 `affect_anchors.py` 同一套方法（semantic projection，Grand et al. 2022），
只是换了几条轴。**构造原则与那边一致**：两侧逐句平行，让均值差里只剩下目标的
那个成分，不要混进话题、句长、人称的差异。

坐标系与效价的区别
------------------
效价/唤醒是**维度情感模型**（Russell 环形模型）规定的两条轴，有实证基础。
下面这些轴是**面向任务的对比轴**——「关心表达 vs 事务处理」不是一个心理学上
公认的维度，它是为了给 LLM 提供输入而构造的。

所以它们的效度层级不同：效价轴有环形模型背书，这些轴没有。**别把它们当同等
可靠的东西用。** 每一组锚句下面都写明了它能支持什么、不能支持什么。

改锚句必须同时 bump `affect_schema.SCHEMA_VERSION`——轴的定义变了，数字就
不可跨版本比。
"""

# ------------------------------------------------------------------ 关心表达轴

# 对比的两极：一端是「把注意力放在对方身上」，另一端是「把注意力放在任务上」。
# 刻意不写成「关心 vs 冷漠」——冷漠不是一个独立的表达方式，而「事务处理」是。
# 用「事务」做对照极，轴上量的才是「这条消息有没有指向对方这个人」。
CARE_POSITIVE = [
    "你最近怎么样，还好吗",
    "记得按时吃饭",
    "天冷了多穿点",
    "你上次说的那件事后来怎么样了",
    "我路过那家店，想起你说过喜欢",
    "早点休息，别熬夜",
    "有事随时找我",
    "你开心就好",
    "需要我帮忙吗",
    "我一直都在的",
]

CARE_NEGATIVE = [
    "文件发我一下",
    "几点开始",
    "链接在哪儿",
    "收到",
    "好了告诉我",
    "这个怎么弄",
    "你看一下对不对",
    "先这样吧",
    "回头再说",
    "按流程走就行",
]

# ------------------------------------------------------------------ 依恋四型

# Bartholomew & Horowitz (1991) 的四分类：焦虑与回避两个维度正交切出四型。
#
# ⚠️ 两组警告，用之前必须知道：
#
# 1. **没有外部效标。** 效价轴至少有表面效度（「恭喜恭喜」落在最正端）可以眼看；
#    「焦虑型轴 0.34」我们**没有任何办法知道它是不是真的对应焦虑**。这四组锚句
#    能给出的只是「这个人的用词离哪一组锚句更近」——它离「依恋类型」还差一次
#    验证，而那次验证做不了。
#
# 2. **恐惧型与回避型在文本上大概率分不开。** 前者的核心是「想靠近又怕」，
#    后者的核心是「不去靠近」——但**说出口的话高度重合**（「算了」「不想说了」
#    「别管我」两边都会说）。区分它们靠的是内部冲突，不是措辞。下面的诊断矩阵
#    会实测这一点。
#
# 因此这一层只能当**给 LLM 的提示**，不能当诊断。项目自己的铁律是「无证据不
# 诊断」——LLM 拿到这四维分数后，仍必须回到原文引用具体句子才能下结论。

ANXIOUS = [
    "你是不是不想理我了",
    "我是不是说太多了",
    "你还在吗",
    "你怎么不回我",
    "对不起，我又烦你了",
    "我这样是不是很讨厌",
    "你别不理我",
    "我是不是哪里做错了",
]

AVOIDANT = [
    "我自己可以",
    "不用麻烦了",
    "随便吧",
    "没什么好说的",
    "都行",
    "我没事",
    "别管我",
    "算了",
]

SECURE = [
    "有事跟我说",
    "我们商量一下",
    "我理解你的意思",
    "你忙你的，我不急",
    "慢慢来，不着急",
    "我支持你",
    "有问题一起解决",
    "谢谢你和我说这些",
]

FEARFUL = [
    "算了，说了也没用",
    "反正你也不会懂",
    "我不想说了",
    "你别问了",
    "我配不上",
    "我不值得",
    "说了你也不明白",
    "算了，当我没说",
]

# 四个极点分成两个维度（焦虑、回避），各自用「该维度的高极 - 低极」构造。
# 注意这里不是直接拿 ANXIOUS 当轴——那样会混进回避成分。
# 焦虑维度的高极=焦虑型+恐惧型，低极=安全型+回避型；
# 回避维度的高极=回避型+恐惧型，低极=安全型+焦虑型。
# **恐惧型同时进两个维度的高极**，这正是它「既焦虑又回避」的定义。
ATTACHMENT_DIMENSIONS = {
    "anxiety": {"high": ANXIOUS + FEARFUL, "low": SECURE + AVOIDANT},
    "avoidance": {"high": AVOIDANT + FEARFUL, "low": SECURE + ANXIOUS},
}
